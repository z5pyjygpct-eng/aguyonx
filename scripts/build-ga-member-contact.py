#!/usr/bin/env python3
"""Build src/content/ga-member-contact.ts from the official LIS public member API
(the same API lis.virginia.gov's member pages use). Fields: first elected (year of LIS
ServiceBeginDate in current chamber), Capitol (General Assembly Building) office, phone, email.
Never uses Mailing/district/home addresses. Blank when LIS doesn't list a value."""
import json, re, urllib.request, datetime
KEY = "FCE351B6-9BD8-46E0-B18F-5572F4CCA5B9"  # public key shipped in lis.virginia.gov front-end JS
API = "https://lis.virginia.gov/Member/api/GetMembersContactInformationListAsync/?sessionCode=20261"
req = urllib.request.Request(API, headers={"WebAPIKey": KEY, "User-Agent": "aguyonx-build"})
rows = json.load(urllib.request.urlopen(req, timeout=60))["MemberContactInformationList"]
by = {r["MemberNumber"]: r for r in rows}
ids = []
for c in ("house", "senate"):
    ids += [m["lisId"] for m in json.load(open(f"src/lib/ga-members-2026-{c}.json"))["members"] if m.get("lisId")]
def fmt_phone(p):
    d = re.sub(r"\D", "", p or "")[-10:]
    return f"({d[:3]}) {d[3:6]}-{d[6:]}" if len(d) == 10 else ((p or "").strip() or None)
out, problems = {}, []
for i in ids:
    r = by.get(i)
    src = f"https://lis.virginia.gov/member-information/{i}/members-legislators"
    if not r:
        out[i] = {"firstElected": None, "office": None, "phone": None, "email": None, "source": src}
        problems.append(f"{i}: not in LIS contact list"); continue
    ga = next((c for c in r["ContactInformation"] if c["ContactType"] == "GA"), None)
    office = None
    if ga and ga.get("Address1"):
        room = (r.get("RoomNumber") or "").strip()
        lines = [f"Room {room}, {ga['Address1']}" if room else ga["Address1"]]
        if ga.get("Address2"): lines.append(ga["Address2"])
        lines.append(f"{ga['City']}, {ga['StateCode']} {ga['ZipCode']}")
        office = lines
    sb = r.get("ServiceBeginDate")
    out[i] = {"firstElected": int(sb[:4]) if sb else None, "office": office,
              "phone": fmt_phone(r.get("GABPhoneNumber")),
              "email": (r.get("GABEmailAddress") or "").strip() or None, "source": src}
    if r["MemberStatus"] != "Active": problems.append(f"{i} {r['FullName']}: LIS status {r['MemberStatus']} ({r['ServiceEndReason']})")
gen = datetime.date.today().isoformat()
ts = f"""// GENERATED by scripts/build-ga-member-contact.py from the official LIS member API ({gen}).
// Owned by the member-contact build, not the routine data refresh. Capitol office only; never home addresses.
export type GaMemberContact = {{ firstElected: number | null; office: string[] | null; phone: string | null; email: string | null; source: string }};
export const GA_CONTACT_GENERATED = "{gen}";
export const GA_MEMBER_CONTACT: Record<string, GaMemberContact> = {json.dumps(out, indent=1)};
"""
open("src/content/ga-member-contact.ts", "w").write(ts)
for ch in "HS":
    sub = [v for k, v in out.items() if k[0] == ch]
    print(ch, len(sub), {f: sum(1 for v in sub if v[f]) for f in ("firstElected", "office", "phone", "email")})
print("\n".join(problems))
