/**
 * Extract public delegate PDFs into a committed search index.
 * Requires poppler pdftotext. Vercel builds do not run this.
 *
 *   node scripts/extract-delegate-pdfs.mjs
 */
import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pdfDir = join(root, "public/files/delegates");
const outFile = join(root, "src/content/delegate-papers.ts");

function collapse(text) {
  return text.replace(/\f/g, " ").replace(/\s+/g, " ").trim();
}

const files = readdirSync(pdfDir)
  .filter((f) => f.endsWith(".pdf"))
  .sort();

const extracts = [];
for (const file of files) {
  const m = file.match(/^(.+)-(tax|energy)\.pdf$/);
  if (!m) {
    console.warn("skip (unexpected name):", file);
    continue;
  }
  const raw = execFileSync("pdftotext", ["-layout", "-enc", "UTF-8", join(pdfDir, file), "-"], {
    encoding: "utf8",
    maxBuffer: 20 * 1024 * 1024,
  });
  extracts.push({
    slug: m[1],
    topic: m[2],
    file,
    text: collapse(raw),
  });
}

const body = extracts
  .map(
    (e) => `  {
    slug: ${JSON.stringify(e.slug)},
    topic: ${JSON.stringify(e.topic)},
    file: ${JSON.stringify(e.file)},
    text: ${JSON.stringify(e.text)},
  }`,
  )
  .join(",\n");

const source = `/** Generated by scripts/extract-delegate-pdfs.mjs from public/files/delegates. Do not edit by hand. */

export type DelegatePaperTopic = "tax" | "energy";

export type DelegatePaperExtract = {
  slug: string;
  topic: DelegatePaperTopic;
  file: string;
  text: string;
};

export const DELEGATE_PAPER_EXTRACTS: DelegatePaperExtract[] = [
${body},
];
`;

writeFileSync(outFile, source);
console.log(`wrote ${outFile} (${extracts.length} papers, ${source.length} bytes)`);
