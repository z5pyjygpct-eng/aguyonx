#!/usr/bin/env python3
"""Hanover + Chesterfield BOS Find the Moment catalogs from the counties' official CivicClerk portals.
Source: https://{site}.api.civicclerk.com/v1/Events (categoryName 'Board of Supervisors', hasMedia).
Writes src/content/civicclerk-counties-data.ts and /tmp/cc-thumbs.json (manifest for scripts/ftm-thumbs.py)."""
import json, os, re, urllib.request, urllib.parse, datetime
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITES = {"hanover-bos": "hanovercova", "chesterfield-bos": "chesterfieldcova"}
def get(u): return json.load(urllib.request.urlopen(urllib.request.Request(u, headers={"User-Agent": "Mozilla/5.0"}), timeout=60))["value"]
out, man = {}, []
for venue, site in SITES.items():
    q = urllib.parse.quote("categoryName eq 'Board of Supervisors' and hasMedia eq true")
    evs, skip = [], 0
    while True:
        v = get(f"https://{site}.api.civicclerk.com/v1/Events?$filter={q}&$orderby=startDateTime%20desc&$skip={skip}")
        if not v: break
        evs += v; skip += len(v)
    rows = []
    for e in evs:
        if not e.get("mediaStreamPath") and not e.get("youtubeVideoId") and not e.get("externalMediaUrl"): continue
        d = datetime.date.fromisoformat(e["startDateTime"][:10])  # CivicClerk stores local wall time
        mins = (e.get("durationHrs") or 0) * 60 + (e.get("durationMin") or 0)
        if not mins and e.get("liveStartTime", "").startswith("2") and e.get("liveEndTime", "").startswith("2"):
            try:
                a = datetime.datetime.fromisoformat(e["liveStartTime"][:19]); b = datetime.datetime.fromisoformat(e["liveEndTime"][:19])
                mins = int((b - a).total_seconds() // 60)
            except Exception: pass
        dur = f"{mins // 60}h {mins % 60:02d}m" if 0 < mins <= 900 else ""
        title = re.sub(r"\s+", " ", e["eventName"]).strip()
        rid = f"{venue}-{e['id']}"
        rows.append({"id": rid, "date": d.isoformat(), "dateLabel": d.strftime("%b %-d, %Y"), "title": title, "duration": dur,
                     "href": f"https://{site}.portal.civicclerk.com/event/{e['id']}/media"})
        man.append({"venue": venue, "id": rid, "out": f"public/thumbs/{venue}/{rid}.webp", "source": e.get("mediaStreamPath"),
                    "duration": dur, "date": d.strftime("%b %-d, %Y"), "type": title})
    out[venue] = rows
    print(venue, len(rows), rows[-1]["date"], rows[0]["date"])
ts = "/** GENERATED by scripts/civicclerk-counties-build.py from the official county CivicClerk portals. Do not hand-edit. */\n"
ts += "export type CcMeeting = { id: string; date: string; dateLabel: string; title: string; duration: string; href: string };\n"
ts += "export const CC_MEETINGS: Record<\"hanover-bos\" | \"chesterfield-bos\", CcMeeting[]> = " + json.dumps(out, indent=0) + ";\n"
ts += f"export const CC_FETCHED = \"{datetime.date.today().isoformat()}\";\n"
open(os.path.join(ROOT, "src/content/civicclerk-counties-data.ts"), "w").write(ts)
json.dump(man, open("/tmp/cc-thumbs.json", "w"))
