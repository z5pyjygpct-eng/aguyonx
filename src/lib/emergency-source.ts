/**
 * Classify Emergency Monitor X sources from link URLs (and a narrow official
 * label pattern). Lists are the classifier — unlisted handles are left
 * unclassifiable rather than guessed. Does not edit the log.
 *
 * Official: government, agency, police, ministry, embassy, elected-office, or
 * operator/status accounts, plus labels of the form "(official)" / "(official,".
 * The word "officials" in news copy is not a signal.
 * News: known news outlets and wires.
 * Other: known OSINT, aggregators, and intel feeds that are not outlets or agencies.
 */

export type SourceClass = "official" | "news" | "other";

