/** "(official)" or "(official," as a label token — not "officials say". */
const OFFICIAL_LABEL = /\(official(?:\)|,)/i;

export function handleFromUrl(url: string | undefined) {
  if (!url) return "";
  const m = url.match(/(?:x\.com|twitter\.com)\/([A-Za-z0-9_]+)/i);
  return m ? m[1].toLowerCase() : "";
}

function classOfLink(url: string | undefined, label: string | undefined): SourceClass | null {
  const handle = handleFromUrl(url);
  const lab = label ?? "";
  if ((handle && OFFICIAL_HANDLES.has(handle)) || OFFICIAL_LABEL.test(lab)) return "official";
  if (handle && NEWS_HANDLES.has(handle)) return "news";
  if (handle && OTHER_HANDLES.has(handle)) return "other";
  return null;
}

/** Classes present on an item's X links. Empty when every link is unlisted, or there are no links. */
export function sourceClassesOf(links: { url?: string; label?: string }[] | undefined): Set<SourceClass> {
  const out = new Set<SourceClass>();
  for (const l of links ?? []) {
    const c = classOfLink(l.url, l.label);
    if (c) out.add(c);
  }
  return out;
}

export function matchesSource(links: { url?: string; label?: string }[] | undefined, source: string) {
  if (!source) return true;
  return sourceClassesOf(links).has(source as SourceClass);
}
