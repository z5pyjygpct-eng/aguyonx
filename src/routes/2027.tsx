const fmtDate = (iso: string) => new Date(iso + "T12:00:00").toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" });

type Status = "contested" | "D" | "R" | "Other" | "unopposed" | "none";
function statusOf(r: Race, office: Office): Status {
  if (!r.candidates.length) return "none";
  if (office === "sb") return r.candidates.length > r.seats ? "contested" : "unopposed";
  const ps = new Set(r.candidates.map((c) => c.party ?? "Other"));
  if (ps.has("D") && ps.has("R")) return "contested";
  if (ps.size === 1) return [...ps][0] as Status;
  return "contested"; // D or R plus another party
}
const isOpen = (r: Race) => !r.candidates.some((c) => c.incumbent);
function incParty(r: Race, office: Office): string | null {
  if (office === "house" || office === "senate") return r.current_member?.party ?? null;
  return r.candidates.find((c) => c.incumbent)?.party ?? null;
}
function matches(r: Race, office: Office, f?: Filter, q?: string) {
  const st = statusOf(r, office);
  if (f === "contested" && st !== "contested") return false;
  if (f === "one" && !["D", "R", "Other", "unopposed"].includes(st)) return false;
  if (f === "none" && st !== "none") return false;
  if (f === "open" && !isOpen(r)) return false;
  if (f === "incD" && incParty(r, office) !== "D") return false;
  if (f === "incR" && incParty(r, office) !== "R") return false;
  if (q) {
    const n = q.toLowerCase().replace(/^(hd|sd)\s*/, "");
    const hay = [r.seat, String(r.district ?? ""), r.locality ?? "", r.body ?? "", ...r.candidates.map((c) => c.name), r.current_member?.name ?? ""].join(" | ").toLowerCase();
    if (/^\d+$/.test(n) ? r.district !== Number(n) : !hay.includes(q.toLowerCase())) return false;
  }
  return true;
}

