const MEMBER_ROUTE = { house: "/dashboards/house/members", senate: "/dashboards/senate/members" } as const;
const lastName = (n: string) => n.replace(/,?\s+(Jr\.?|Sr\.?|II|III|IV)$/i, "").trim().split(/\s+/).pop()!.toLowerCase();

function CandLine({ c, r, office }: { c: Cand; r: Race; office: Office }) {
  const file = CANDIDATES_2027.find((x) => x.name.toLowerCase() === c.name.toLowerCase());
  const member = (office === "house" || office === "senate") && c.incumbent && r.current_member && lastName(r.current_member.name) === lastName(c.name) ? r.current_member : null;
  return (
    <li className="leading-snug">
      <span className="font-semibold text-white">{c.name}{c.incumbent ? <span className="text-gold" aria-label="incumbent">*</span> : null}</span>
      {c.endorsement && c.party_source_url ? <a href={c.party_source_url} target="_blank" rel="noopener noreferrer" className="ml-1 text-xs text-gold underline">{c.endorsement}</a> : null}
      {member ? <Link to={`${MEMBER_ROUTE[office as "house" | "senate"]}/${member.slug}` as never} className="ml-2 text-xs text-gold underline">member file</Link> : null}
      {file ? <a href={`#file-${file.id}`} className="ml-2 text-xs text-gold underline">our file</a> : null}
    </li>
  );
}

