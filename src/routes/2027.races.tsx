function covNote(e: Entry, locs: string[]) {
  const cs: Coverage[] = (e.race.localities ?? []).filter((l) => !locs.length || locs.includes(l.locality_id));
  return cs.length ? cs.map((l) => `includes ${l.coverage === "all" ? "all" : "part"} of ${l.locality}`).join(" · ") : null;
}

