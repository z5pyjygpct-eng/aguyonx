/** Page-level deep search (?q=), placed at the top like the bills tracker and Emergency Monitor. Results are races. */
function TopSearch({ s }: { s: S }) {
  const navigate = Route.useNavigate();
  const today = useMemo(() => todayET(), []);
  const [text, setText] = useState(s.q ?? "");
  useEffect(() => setText(s.q ?? ""), [s.q]);
  const f = dirFilters(s, today);
  const terms = useMemo(() => (s.q ? parseQuery(s.q) : []), [s.q]);
  const hits = useMemo(() => (s.q ? filterEntries(ENTRIES, f) : []), [s.q, s.r_office, s.r_loc, s.r_status, s.r_party, s.r_filed]); // eslint-disable-line react-hooks/exhaustive-deps
  const pills = !!(s.r_office || s.r_loc || s.r_status || s.r_party || s.r_filed);
  const setQ = (v: string) => { setText(v); navigate({ search: (p: S) => ({ ...p, q: v.trim() ? v.slice(0, 80) : undefined, seat: undefined }), replace: true, resetScroll: false }); };
  const SHOW = 12;
  return (
    <section className="mt-4 rounded-xl border border-navy-line bg-navy-700 p-4 sm:p-5" aria-label="Search races">
      <form role="search" onSubmit={(e) => e.preventDefault()}>
        <label htmlFor="q2027" className="font-serif text-[11px] tracking-[0.14em] text-night-muted uppercase">Search every race: names, districts, localities, offices, party or status</label>
        <div className="mt-1 flex items-center gap-2 rounded-xl border border-navy-line bg-navy-800 px-3 focus-within:border-gold">
          <Search className="size-4 shrink-0 text-gold" aria-hidden />
          <input id="q2027" type="search" value={text} onChange={(e) => setQ(e.target.value)} autoComplete="off"
            placeholder="Try a name, district, or county: Helmer, HD 30, Loudoun" className="h-12 w-full min-w-0 bg-transparent text-base text-white placeholder:text-night-muted focus:outline-none" />
          {text ? <button type="button" onClick={() => setQ("")} aria-label="Clear search" className="rounded-md p-1 text-gold hover:bg-navy-600"><X className="size-4" /></button> : null}
        </div>
      </form>
      {s.q ? (
        <div className="mt-3" id="search-results">
          <p className="text-sm font-semibold text-[#F6F3EA]" role="status" aria-live="polite">{summary(hits.length, s.q)}{pills ? " with the filters picked below" : ""}</p>
          {hits.length ? (
            <ul className="mt-2 space-y-2">{hits.slice(0, SHOW).map((e) => <RaceRow key={e.office + e.race.id} e={e} today={today} terms={terms} locs={toFilters(s).localities} card />)}</ul>
          ) : <p className="mt-1 text-sm text-on-dark-muted">No race matches. Try a last name, a district number such as HD 30 or SD 31, or a county.</p>}
          {hits.length > SHOW ? <p className="mt-2 text-sm"><a href="#races" className="text-gold underline">See all {hits.length} matching races in the race list below</a></p> : null}
        </div>
      ) : <p className="mt-2 text-xs text-night-muted">Matches registered candidates and committees, current members, partial or misspelled names, district numbers (HD 30, SD 31, District 30), offices, localities, magisterial districts, party and status words (contested, member not filed, no filing).</p>}
    </section>
  );
}

