/** Directory filters = the pills plus the page-level deep search (?q=). */
function dirFilters(s: S, today: ReturnType<typeof todayET>) {
  const f = toFilters(s, today);
  return { ...f, q: s.q ?? "", ...(s.q ? { match: (e: Entry) => raceMatchesQuery(e, s.q!) } : {}) };
}

