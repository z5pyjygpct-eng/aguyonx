import { useMemo, useState, type ReactNode } from "react";
import { createFileRoute, Link } from "@tanstack/react-router";
import { AlertTriangle, ArrowRight, ArrowUpRight, ChevronDown, Download, Search } from "lucide-react";
import { SiteShell } from "@/components/site/shell";
import { V4Main } from "@/components/site/lcps-v4";
import { V4VenueHero } from "@/components/site/venue-v4";
import { LIBRARY } from "@/content/library";
import type { LibraryItem } from "@/content/types";
import { SHELVES, START_HERE, shelfOf, type ShelfId } from "@/lib/library-shelves";
import OSINT from "@/lib/osint-va.json";
import { cn } from "@/lib/utils";

/**
 * Research Library (v4 preview). 98 library items on 7 shelves + 204 Virginia research sources (22 categories,
 * generated by tools/library/build_osint.py; 22 duplicates of library items are merged into the library entry).
 * URL: ?cat=<shelf id | va> and ?q=<text>. Nothing is hidden for good: every item is on its shelf's full view,
 * the All view, and search. /library/foia is a separate route and unchanged.
 */
type Cat = ShelfId | "va";
const CAT_IDS = new Set<string>([...SHELVES.map((s) => s.id), "va"]);
type LibSearch = { cat?: Cat; q?: string };

export const Route = createFileRoute("/library/")({
  validateSearch: (s: Record<string, unknown>): LibSearch => ({
    ...(typeof s.cat === "string" && CAT_IDS.has(s.cat) ? { cat: s.cat as Cat } : {}),
    ...(typeof s.q === "string" && s.q.trim() ? { q: s.q.slice(0, 120) } : {}),
  }),
  head: () => ({ meta: [{ title: "Research Library · A Guy on X" }] }),
  component: LibraryIndex,
});

type VaItem = { name: string; url: string; note: string; paid: boolean; check: string };
type VaCat = { name: string; items: VaItem[]; merged: { name: string; url: string; existingSlug: string; existingTitle: string }[] };
const VA = OSINT.categories as VaCat[];
const VA_COUNT = VA.reduce((a, c) => a + c.items.length, 0);
const COURTS = "VA Courts";

const byNewest = (a: LibraryItem, b: LibraryItem) => b.date.localeCompare(a.date) || a.title.localeCompare(b.title);
const ITEMS = [...LIBRARY].sort(byNewest);
const BY_SLUG = new Map(LIBRARY.map((i) => [i.slug, i]));
const SHELF_ITEMS = Object.fromEntries(SHELVES.map((s) => [s.id, ITEMS.filter((i) => shelfOf(i) === s.id)])) as Record<ShelfId, LibraryItem[]>;

const slugify = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
function domain(u?: string) {
  if (!u || !/^https?:/.test(u)) return "aguyonx.com";
  try { return new URL(u).hostname.replace(/^www\./, ""); } catch { return u; }
}
const kindLabel = (k: string) => ({ government: "Government", news: "News", "research-tool": "Research tool", tool: "Tool" })[k] ?? k;
const norm = (s: string) => s.toLowerCase();
function libMatch(i: LibraryItem, q: string) {
  return [i.title, i.source, i.summary, domain(i.href ?? i.file ?? i.tool)].some((f) => norm(f).includes(q));
}
function vaMatch(c: VaCat, i: VaItem, q: string) {
  return [i.name, i.note, c.name, domain(i.url)].some((f) => norm(f).includes(q));
}

const tileCls = "group relative flex h-full min-w-0 flex-col rounded-[10px] border border-navy-line border-t-[3px] border-t-gold bg-navy-700 p-4 pr-10 text-white transition-colors hover:bg-navy-600 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-gold";
const ext = { target: "_blank", rel: "noopener noreferrer" } as const;

function ItemTile({ item }: { item: LibraryItem }) {
  const body = (icon: ReactNode) => (
    <>
      {icon}
      <span className="w-fit rounded bg-navy-900/70 px-1.5 py-0.5 font-mono text-[10px] tracking-wider text-gold uppercase">{kindLabel(item.kind)}</span>
      <span className="mt-2 font-serif text-lg font-semibold leading-snug">{item.title}</span>
      {item.summary && item.summary !== "Official public record." ? <span className="mt-1 line-clamp-2 text-sm text-on-dark-muted">{item.summary}</span> : null}
      <span className="mt-auto truncate pt-3 font-mono text-[11px] text-night-muted">{domain(item.href ?? item.file)} · {item.displayDate}</span>
    </>
  );
  const arrow = (I: typeof ArrowRight) => <I className="absolute top-4 right-3 size-5 text-gold transition-transform group-hover:translate-x-0.5" aria-hidden />;
  if (item.tool) return <Link to="/library/foia" className={tileCls}>{body(arrow(ArrowRight))}</Link>;
  if (item.file) return <a href={item.file} download className={tileCls}>{body(arrow(Download))}</a>;
  return <a href={item.href} {...ext} className={tileCls}>{body(arrow(ArrowUpRight))}</a>;
}

function Grid({ items }: { items: LibraryItem[] }) {
  return (
    <ul className="mt-4 grid grid-cols-1 gap-3 sm:grid-cols-2 lg:grid-cols-5 sm:gap-4">
      {items.map((i) => <li key={i.slug} className="min-w-0"><ItemTile item={i} /></li>)}
    </ul>
  );
}

/** Top 5 per shelf: swipe row on phones, 5-up grid from sm up. */
function Row({ items, inset }: { items: LibraryItem[]; inset?: boolean }) {
  return (
    <ul className={cn("mt-4 flex", inset ? "" : "-mx-4 px-4") + " snap-x snap-mandatory gap-3 overflow-x-auto pb-2 sm:mx-0 sm:grid sm:snap-none sm:grid-cols-3 sm:overflow-visible sm:px-0 sm:pb-0 lg:grid-cols-5 sm:gap-4"}>
      {items.map((i) => <li key={i.slug} className="w-[72%] shrink-0 snap-start sm:w-auto"><ItemTile item={i} /></li>)}
    </ul>
  );
}

function Chip({ active, to, children, count }: { active: boolean; to: LibSearch; children: ReactNode; count: number }) {
  return (
    <Link
      to="/library"
      search={to}
      resetScroll={false}
      aria-current={active ? "true" : undefined}
      className={cn(
        "inline-flex h-9 shrink-0 items-center gap-1.5 rounded-full border px-3 text-sm font-semibold whitespace-nowrap transition-colors",
        active ? "border-gold bg-gold text-navy-900" : "border-navy-line bg-navy-700 text-white hover:border-gold",
      )}
    >
      {children}
      <span className={cn("rounded-full px-1.5 text-xs", active ? "bg-navy-900/15" : "bg-navy-900/60 text-gold")}>{count}</span>
    </Link>
  );
}

function SectionHead({ title, count, more }: { title: string; count: number; more?: LibSearch }) {
  return (
    <div className="flex items-end justify-between gap-3 border-b border-navy-line pb-2">
      <h2 className="font-serif text-2xl font-semibold uppercase sm:text-3xl">{title} <span className="align-middle font-mono text-sm text-gold">{count}</span></h2>
      {more ? <Link to="/library" search={more} className="shrink-0 text-sm font-semibold text-gold hover:underline">See all {count} →</Link> : null}
    </div>
  );
}

function Paid() {
  return <span className="ml-2 inline-block rounded bg-gold/15 px-1.5 py-px align-middle font-mono text-[10px] font-bold tracking-wider text-gold uppercase ring-1 ring-gold/50">Paid</span>;
}

function CourtsCaution() {
  return (
    <p className="mb-3 flex gap-2 rounded-md border border-gold/60 bg-gold/10 px-3 py-2 text-sm text-[#F6F3EA]">
      <AlertTriangle className="mt-0.5 size-4 shrink-0 text-gold" aria-hidden />
      <span><span className="font-semibold text-gold">Court-record caution:</span> OCIS is the go-to statewide search, but a name match is not a person match. Confirm with date of birth, middle name/initial, address, or case details before relying on it. Fairfax Circuit and Alexandria Circuit are not in OCIS.</span>
    </p>
  );
}

function VaSection({ q, openAll }: { q: string; openAll: boolean }) {
  const cats = q ? VA.map((c) => ({ ...c, items: c.items.filter((i) => vaMatch(c, i, q)) })).filter((c) => c.items.length) : VA;
  const [open, setOpen] = useState<Set<string>>(() => new Set());
  const isOpen = (n: string) => openAll || !!q || open.has(n);
  const toggle = (n: string, v: boolean) => setOpen((s) => { const x = new Set(s); v ? x.add(n) : x.delete(n); return x; });
  if (q && !cats.length) return null;
  const shown = cats.reduce((a, c) => a + c.items.length, 0);
  return (
    <section id="va-sources" className="mt-14 scroll-mt-24" aria-labelledby="va-title">
      <div className="rounded-[10px] border border-navy-line border-t-4 border-t-gold bg-navy-700 p-5 sm:p-6">
        <p className="font-mono text-xs tracking-widest text-gold uppercase">Virginia research sources</p>
        <h2 id="va-title" className="mt-1 font-serif text-3xl font-semibold uppercase">Dig deeper <span className="align-middle font-mono text-sm text-gold">{shown}</span></h2>
        <p className="mt-2 max-w-3xl text-sm text-[#F6F3EA]">
          More places to look things up: courts, land records, schools, local governments, businesses and more, sorted into {VA.length} groups. Tap a group to open it.
          <span className="font-semibold text-gold"> Paid</span> means some or all of it costs money.
        </p>
        {!q ? (
          <nav aria-label="Virginia research source groups" className="mt-4 flex flex-wrap gap-2">
            {VA.map((c) => (
              <a key={c.name} href={`#va-${slugify(c.name)}`} onClick={() => toggle(c.name, true)} className="inline-flex h-8 items-center gap-1 rounded-full border border-navy-line bg-navy-800 px-3 text-xs font-semibold text-white hover:border-gold">
                {c.name} <span className="text-gold">{c.items.length}</span>
              </a>
            ))}
          </nav>
        ) : null}
      </div>
      <div className="mt-4 space-y-2">
        {cats.map((c) => (
          <details key={c.name} id={`va-${slugify(c.name)}`} open={isOpen(c.name)} onToggle={(e) => { const v = (e.currentTarget as HTMLDetailsElement).open; if (v !== isOpen(c.name)) toggle(c.name, v); }} className="group/d scroll-mt-24 rounded-[10px] border border-navy-line bg-navy-700 open:border-t-[3px] open:border-t-gold">
            <summary className="flex cursor-pointer list-none items-center justify-between gap-3 px-4 py-3 [&::-webkit-details-marker]:hidden">
              <span className="font-serif text-xl font-semibold uppercase">{c.name} <span className="font-mono text-sm text-gold">{c.items.length}</span></span>
              <ChevronDown className="size-5 shrink-0 text-gold transition-transform group-open/d:rotate-180" aria-hidden />
            </summary>
            <div className="border-t border-navy-line px-4 py-3">
              {c.name === COURTS ? <CourtsCaution /> : null}
              <ul className="grid gap-x-6 gap-y-3 md:grid-cols-2">
                {c.items.map((i) => (
                  <li key={i.url} className="min-w-0">
                    <a href={i.url} {...ext} className="group/l inline font-semibold text-white [overflow-wrap:anywhere] hover:text-gold">
                      {i.name}<ArrowUpRight className="ml-1 inline size-4 text-gold" aria-hidden />
                    </a>
                    {i.paid ? <Paid /> : null}
                    <p className="text-sm leading-snug text-on-dark-muted">{i.note}</p>
                  </li>
                ))}
              </ul>
              {!q && c.merged.length ? (
                <p className="mt-3 text-xs text-night-muted">
                  Also on the shelves above:{" "}
                  {c.merged.map((m, k) => {
                    const it = BY_SLUG.get(m.existingSlug);
                    return <span key={m.url}>{k ? ", " : ""}<a href={it?.href ?? m.url} {...ext} className="text-gold hover:underline">{it?.title ?? m.existingTitle}</a></span>;
                  })}
                </p>
              ) : null}
            </div>
          </details>
        ))}
      </div>
    </section>
  );
}

function LibraryIndex() {
  const { cat, q: qRaw } = Route.useSearch();
  const navigate = Route.useNavigate();
  const [text, setText] = useState(qRaw ?? "");
  const q = norm((qRaw ?? "").trim());
  const shelf = cat && cat !== "va" ? cat : undefined;

  const libHits = useMemo(() => (q ? ITEMS.filter((i) => libMatch(i, q) && (!shelf || shelfOf(i) === shelf)) : []), [q, shelf]);
  const total = LIBRARY.length + VA_COUNT;
  const setQ = (v: string) => {
    setText(v);
    navigate({ search: (s: LibSearch) => ({ ...s, q: v.trim() ? v : undefined }), replace: true, resetScroll: false });
  };

  return (
    <SiteShell>
      <V4Main>
        <V4VenueHero venue={{ crumbs: [{ label: "Other Resources" }], titleA: "Research", titleB: "Library", foia: { label: "", href: "" } }} kicker="Research Library" />
        <div className="mx-auto max-w-7xl px-4 py-8 sm:px-8">
          <p className="max-w-3xl text-base text-[#F6F3EA]">{total} public sources in one place. Official records first. Search everything, or pick a shelf.</p>

          <form role="search" onSubmit={(e) => e.preventDefault()} className="mt-5">
            <label htmlFor="lib-q" className="sr-only">Search the library</label>
            <div className="flex items-center gap-2 rounded-[10px] border border-navy-line bg-navy-700 px-3 focus-within:border-gold">
              <Search className="size-5 shrink-0 text-gold" aria-hidden />
              <input id="lib-q" type="search" value={text} onChange={(e) => setQ(e.target.value)} placeholder={`Search ${total} sources — try "campaign finance", "FOIA", "Loudoun"`} className="h-12 w-full min-w-0 bg-transparent text-base text-white placeholder:text-night-muted focus:outline-none" />
            </div>
          </form>

          <nav aria-label="Library shelves" className="-mx-4 mt-4 flex gap-2 overflow-x-auto px-4 pb-1 sm:mx-0 sm:flex-wrap sm:overflow-visible sm:px-0">
            <Chip active={!cat} to={q ? { q: qRaw } : {}} count={LIBRARY.length}>All</Chip>
            {SHELVES.map((s) => <Chip key={s.id} active={cat === s.id} to={{ cat: s.id, ...(q ? { q: qRaw } : {}) }} count={SHELF_ITEMS[s.id].length}>{s.label}</Chip>)}
            <Chip active={cat === "va"} to={{ cat: "va", ...(q ? { q: qRaw } : {}) }} count={VA_COUNT}>Virginia research sources</Chip>
          </nav>

          {q ? (
            <>
              {cat !== "va" ? (
                <section className="mt-8">
                  <SectionHead title={shelf ? `${SHELVES.find((s) => s.id === shelf)!.label}: matches` : "Library matches"} count={libHits.length} />
                  {libHits.length ? <Grid items={libHits} /> : <p className="mt-3 text-sm text-on-dark-muted">No shelf items match "{qRaw}".</p>}
                </section>
              ) : null}
              {!shelf ? <VaSection q={q} openAll /> : null}
            </>
          ) : shelf ? (
            <section className="mt-8">
              <SectionHead title={SHELVES.find((s) => s.id === shelf)!.label} count={SHELF_ITEMS[shelf].length} />
              <Grid items={SHELF_ITEMS[shelf]} />
            </section>
          ) : cat === "va" ? (
            <VaSection q="" openAll />
          ) : (
            <>
              <section className="mt-8 rounded-[10px] border border-flag/70 bg-navy-900/40 p-4 sm:p-5">
                <div className="flex items-end justify-between"><h2 className="font-serif text-2xl font-semibold uppercase">Start here</h2><span className="text-sm text-gold">{START_HERE.length} picks</span></div>
                <Row inset items={START_HERE.map((s) => BY_SLUG.get(s)).filter((x): x is LibraryItem => !!x)} />
              </section>
              {SHELVES.map((s) => (
                <section key={s.id} className="mt-10">
                  <SectionHead title={s.label} count={SHELF_ITEMS[s.id].length} more={{ cat: s.id }} />
                  <Row items={SHELF_ITEMS[s.id].slice(0, 5)} />
                </section>
              ))}
              <VaSection q="" openAll={false} />
            </>
          )}
        </div>
      </V4Main>
    </SiteShell>
  );
}
